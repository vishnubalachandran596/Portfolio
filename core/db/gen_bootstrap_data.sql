-- Emits an idempotent, data-only seed script for the content tables, read from
-- a live database. This file is the durable artifact; its output is a snapshot.
--
--   psql "$DATABASE_URL" -AtX -v ON_ERROR_STOP=1 -f core/db/gen_bootstrap_data.sql \
--        > /tmp/portfolio_seed_data.sql
--
-- The output does NOT live in this repo (rule 9): it is uploaded to the Google
-- Drive folder named `Portfolio` as `portfolio_seed_data.sql`. The generator
-- stays here because it is code, not content, and because the alternative -- a
-- hand-maintained seed file -- drifts from the live database within a week.
--
-- Schema is deliberately NOT emitted. core/db/migrations/ owns the schema, and
-- a second copy here would be a second source of truth that drifts.
--
-- Personal and transactional tables are deliberately NOT emitted either:
-- admins, users, purchases, bookings, quiz_attempts, contact_messages,
-- article_thumbs_up, testimonials, promo_codes, promo_code_courses,
-- admin_messages, course_updates, audit_requests. They are not content, they
-- carry third-party PII, and a fresh install should not have them. The first
-- admin account is created by Bootstrap() from ADMIN_BOOTSTRAP_EMAIL /
-- ADMIN_BOOTSTRAP_PASSWORD -- see the generated header for the procedure. No
-- password hash is ever emitted.
--
-- Every emitted statement is a single INSERT guarded by WHERE NOT EXISTS on the
-- row's natural key, with the UPDATE of an existing row folded into the same
-- statement as a CTE. Deliberately NOT `ON CONFLICT`: skill_groups,
-- experiences, education, home_features, availability_rules, quiz_questions,
-- certifications and publications have no unique constraint on their natural
-- key, so `ON CONFLICT` there is either a syntax error (with a target) or a
-- silent no-op that duplicates every row (without one -- the SERIAL primary key
-- draws a fresh value on every pass, so it can never conflict). The
-- WHERE NOT EXISTS form needs no constraint and cannot duplicate.
--
-- The VALUES-CTE shape is what lets each literal appear exactly once. An
-- article body is ~10 KB; writing it into both an UPDATE and an INSERT would
-- double the file for no benefit and give two places for an edit to go wrong.
-- The UPDATE's `FROM v` and the INSERT's `WHERE NOT EXISTS` both read the
-- statement's own snapshot, so exactly one of the two ever affects a row.

-- Two optional settings, for the case where the generator cannot be pointed
-- straight at the live database. Running it from a Cloud Agent, the live
-- DATABASE_URL is only in Vercel's encrypted environment, so the alternative is
-- to mirror the live content into a scratch database, prove the mirror matches
-- with a per-table md5 fingerprint, and generate from that. When that happens,
-- the header must still name the real source rather than the scratch database,
-- and it must say how the mirror was proved -- otherwise the snapshot looks
-- like it came from somewhere it did not.
--
--   psql ... -c "SET portfolio.source_db = 'postgres'" \
--            -c "SET portfolio.provenance = 'how the mirror was verified'" \
--            -f core/db/gen_bootstrap_data.sql
--
-- Unset (the normal case, connected directly to the live database),
-- current_database() is the source and no provenance note is emitted.

\pset footer off

SELECT '-- portfolio_seed_data.sql'
    || E'\n-- Content snapshot of the Portfolio site database. Generated '
    || now()::date
    || E'.\n--'
    || E'\n-- Source database: `'
    || coalesce(nullif(current_setting('portfolio.source_db', true), ''), current_database())
    || '` (the live Supabase project).'
    || E'\n-- Generated by core/db/gen_bootstrap_data.sql in the Portfolio repo.'
    || coalesce(E'\n-- Provenance: ' || nullif(current_setting('portfolio.provenance', true), ''), '')
    || E'\n--'
    || E'\n-- REGENERATE (from the repo root, with DATABASE_URL in your shell or'
    || E'\n-- an untracked .env -- never committed, never pasted into this file):'
    || E'\n--'
    || E'\n--   psql "$DATABASE_URL" -AtX -v ON_ERROR_STOP=1 \\'
    || E'\n--        -f core/db/gen_bootstrap_data.sql > portfolio_seed_data.sql'
    || E'\n--'
    || E'\n-- RUN IT against an empty or existing database:'
    || E'\n--'
    || E'\n--   1. Create the schema first. The migration chain owns it:'
    || E'\n--        DATABASE_URL=... go run ./cmd/server     # applies migrations, then Ctrl-C'
    || E'\n--      Or apply core/db/migrations/*.sql in filename order by hand.'
    || E'\n--   2. Load this file:'
    || E'\n--        psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f portfolio_seed_data.sql'
    || E'\n--'
    || E'\n-- Safe to run repeatedly. Every insert is guarded by WHERE NOT EXISTS on the'
    || E'\n-- row''s natural key, and an existing row is updated in the same statement, so a'
    || E'\n-- second pass changes nothing and a stale row is brought up to date.'
    || E'\n--'
    || E'\n-- ADMIN LOGIN -- read this before wondering why you cannot log in.'
    || E'\n-- This file contains NO admins row and NO password hash, on purpose: a'
    || E'\n-- credential does not belong in a content snapshot. A fresh database therefore'
    || E'\n-- has no admin, and nothing in the admin console is reachable. The app creates'
    || E'\n-- the first one for you: set ADMIN_BOOTSTRAP_EMAIL and ADMIN_BOOTSTRAP_PASSWORD'
    || E'\n-- in the environment and start the app once. Bootstrap() (core/app/bootstrap.go)'
    || E'\n-- creates the account on the next cold start when the admins table is empty,'
    || E'\n-- and is a no-op once an admin exists. Then log in at /admin/login and rotate'
    || E'\n-- the password.'
    || E'\n--'
    || E'\n-- COURSE HTML is not in this file. courses.content_object is a path inside'
    || E'\n-- the private Supabase Storage bucket course-content (courses/<slug>.html).'
    || E'\n-- courses.content_html is a legacy column and stays empty. Restoring these'
    || E'\n-- rows does not restore the lesson bytes; those live only in the bucket.'
    || E'\n--'
    || E'\n-- DIRECTION OF TRUTH: the live database is authoritative. Content is edited in'
    || E'\n-- the admin console, and this file is regenerated from the database afterwards.'
    || E'\n-- Editing this file does not change the site.'
    || E'\n'
    || E'\nBEGIN;\n';

-- Duplicate rows cannot come from this file, but they can already exist in a
-- target database seeded by an older, unguarded migration (this is exactly how
-- production ended up with quiz_questions duplicated 2x). Collapse them on the
-- natural key, keeping the lowest id, before anything below matches on it.
-- Self-limiting: nothing is left to delete on a second pass.
SELECT E'-- de-duplicate on natural keys before matching on them ---------------\n'
    || E'DELETE FROM quiz_questions q USING quiz_questions dup\n'
    || E' WHERE q.course_id = dup.course_id AND q.question = dup.question AND q.id > dup.id;\n'
    || E'DELETE FROM skill_groups s USING skill_groups dup\n'
    || E' WHERE s.category = dup.category AND s.id > dup.id;\n'
    || E'DELETE FROM experiences e USING experiences dup\n'
    || E' WHERE e.company = dup.company AND e.role = dup.role AND e.start_date = dup.start_date AND e.id > dup.id;\n'
    || E'DELETE FROM education e USING education dup\n'
    || E' WHERE e.institution = dup.institution AND e.degree = dup.degree AND e.field = dup.field AND e.id > dup.id;\n'
    || E'DELETE FROM home_features h USING home_features dup\n'
    || E' WHERE h.title = dup.title AND h.id > dup.id;\n'
    || E'DELETE FROM availability_rules a USING availability_rules dup\n'
    || E' WHERE a.weekday = dup.weekday AND a.start_time = dup.start_time AND a.end_time = dup.end_time AND a.id > dup.id;\n';

-- profile: a single identity row pinned to id = 1 by a CHECK constraint.
SELECT E'\n-- profile -------------------------------------------------------------';
SELECT format($f$
WITH v (name, title, tagline, hero_subtitle, summary, location, email, linkedin_url, github_url, resume_url, photo_url, years_experience) AS (
  VALUES (%L::text, %L::text, %L::text, %L::text, %L::text, %L::text, %L::text, %L::text, %L::text, %L::text, %L::text, %s::smallint)
), upd AS (
  UPDATE profile p SET name = v.name, title = v.title, tagline = v.tagline,
      hero_subtitle = v.hero_subtitle, summary = v.summary, location = v.location,
      email = v.email, linkedin_url = v.linkedin_url, github_url = v.github_url,
      resume_url = v.resume_url, photo_url = v.photo_url,
      years_experience = v.years_experience, updated_at = now()
    FROM v WHERE p.id = 1 RETURNING 1
)
INSERT INTO profile (id, name, title, tagline, hero_subtitle, summary, location, email, linkedin_url, github_url, resume_url, photo_url, years_experience)
SELECT 1, v.* FROM v WHERE NOT EXISTS (SELECT 1 FROM profile WHERE id = 1);$f$,
  name, title, tagline, hero_subtitle, summary, location, email,
  linkedin_url, github_url, resume_url, photo_url, years_experience)
FROM profile WHERE id = 1;

-- skill_groups: natural key is `category`.
SELECT E'\n-- skill_groups --------------------------------------------------------';
SELECT format($f$
WITH v (category, level, achievement, items, sort_order) AS (
  VALUES (%L::text, %L::text, %L::text, %L::text, %s::int)
), upd AS (
  UPDATE skill_groups s SET level = v.level, achievement = v.achievement,
      items = v.items, sort_order = v.sort_order
    FROM v WHERE s.category = v.category RETURNING 1
)
INSERT INTO skill_groups (category, level, achievement, items, sort_order)
SELECT v.* FROM v WHERE NOT EXISTS (SELECT 1 FROM skill_groups s WHERE s.category = v.category);$f$,
  category, level, achievement, items, sort_order)
FROM skill_groups ORDER BY sort_order, id;

-- experiences: natural key is (company, role, start_date) -- a second stint at
-- the same employer in a different role, or the same role starting later, is a
-- genuinely separate row.
SELECT E'\n-- experiences ---------------------------------------------------------';
SELECT format($f$
WITH v (company, role, location, start_date, end_date, bullets, sort_order) AS (
  VALUES (%L::text, %L::text, %L::text, %L::text, %L::text, %L::text, %s::int)
), upd AS (
  UPDATE experiences e SET location = v.location, end_date = v.end_date,
      bullets = v.bullets, sort_order = v.sort_order
    FROM v WHERE e.company = v.company AND e.role = v.role AND e.start_date = v.start_date
    RETURNING 1
)
INSERT INTO experiences (company, role, location, start_date, end_date, bullets, sort_order)
SELECT v.* FROM v WHERE NOT EXISTS (
  SELECT 1 FROM experiences e WHERE e.company = v.company AND e.role = v.role AND e.start_date = v.start_date);$f$,
  company, role, location, start_date, end_date, bullets, sort_order)
FROM experiences ORDER BY sort_order, id;

-- education: natural key is (institution, degree, field). start_year/end_year
-- are nullable, so %s with a coalesce to the bare NULL keyword rather than %L.
SELECT E'\n-- education -----------------------------------------------------------';
SELECT format($f$
WITH v (institution, degree, field, start_year, end_year, details, sort_order) AS (
  VALUES (%L::text, %L::text, %L::text, %s::int, %s::int, %L::text, %s::int)
), upd AS (
  UPDATE education e SET start_year = v.start_year, end_year = v.end_year,
      details = v.details, sort_order = v.sort_order
    FROM v WHERE e.institution = v.institution AND e.degree = v.degree AND e.field = v.field
    RETURNING 1
)
INSERT INTO education (institution, degree, field, start_year, end_year, details, sort_order)
SELECT v.* FROM v WHERE NOT EXISTS (
  SELECT 1 FROM education e WHERE e.institution = v.institution AND e.degree = v.degree AND e.field = v.field);$f$,
  institution, degree, field, coalesce(start_year::text, 'NULL'),
  coalesce(end_year::text, 'NULL'), details, sort_order)
FROM education ORDER BY sort_order, id;

-- home_features: natural key is `title`.
SELECT E'\n-- home_features -------------------------------------------------------';
SELECT format($f$
WITH v (title, description, sort_order) AS (
  VALUES (%L::text, %L::text, %s::int)
), upd AS (
  UPDATE home_features h SET description = v.description, sort_order = v.sort_order
    FROM v WHERE h.title = v.title RETURNING 1
)
INSERT INTO home_features (title, description, sort_order)
SELECT v.* FROM v WHERE NOT EXISTS (SELECT 1 FROM home_features h WHERE h.title = v.title);$f$,
  title, description, sort_order)
FROM home_features ORDER BY sort_order, id;

-- courses: natural key is `slug`. content_html stays empty. content_object is
-- the Storage path; the HTML bytes are not in this file.
SELECT E'\n-- courses -------------------------------------------------------------';
SELECT format($f$
WITH v (slug, title, summary, description, level, duration, price_cents, currency, image_url, is_published, sort_order, is_paid, min_price_cents, min_price_cents_inr, content_key, content_object, content_html) AS (
  VALUES (%L::text, %L::text, %L::text, %L::text, %L::text, %L::text, %s::int, %L::text, %L::text, %L::boolean, %s::int, %L::boolean, %s::int, %s::int, %L::text, %L::text, %L::text)
), upd AS (
  UPDATE courses c SET title = v.title, summary = v.summary, description = v.description,
      level = v.level, duration = v.duration, price_cents = v.price_cents,
      currency = v.currency, image_url = v.image_url, is_published = v.is_published,
      sort_order = v.sort_order, is_paid = v.is_paid, min_price_cents = v.min_price_cents,
      min_price_cents_inr = v.min_price_cents_inr, content_key = v.content_key,
      content_object = v.content_object, content_html = v.content_html, updated_at = now()
    FROM v WHERE c.slug = v.slug RETURNING 1
)
INSERT INTO courses (slug, title, summary, description, level, duration, price_cents, currency, image_url, is_published, sort_order, is_paid, min_price_cents, min_price_cents_inr, content_key, content_object, content_html)
SELECT v.* FROM v WHERE NOT EXISTS (SELECT 1 FROM courses c WHERE c.slug = v.slug);$f$,
  slug, title, summary, description, level, duration, price_cents, currency, image_url,
  is_published, sort_order, is_paid, min_price_cents, min_price_cents_inr, content_key, content_object, content_html)
FROM courses ORDER BY sort_order, id;

-- articles: natural key is `slug`. thumbs_up_count is deliberately omitted --
-- it is a running tally of visitor activity, not content, and the matching
-- article_thumbs_up rows are not emitted either.
SELECT E'\n-- articles ------------------------------------------------------------';
SELECT format($f$
WITH v (slug, title, summary, body, cover_image_url, tags, published_date, is_published, sort_order) AS (
  VALUES (%L::text, %L::text, %L::text, %L::text, %L::text, %L::text[], %s::date, %L::boolean, %s::int)
), upd AS (
  UPDATE articles a SET title = v.title, summary = v.summary, body = v.body,
      cover_image_url = v.cover_image_url, tags = v.tags,
      published_date = v.published_date, is_published = v.is_published,
      sort_order = v.sort_order
    FROM v WHERE a.slug = v.slug RETURNING 1
)
INSERT INTO articles (slug, title, summary, body, cover_image_url, tags, published_date, is_published, sort_order)
SELECT v.* FROM v WHERE NOT EXISTS (SELECT 1 FROM articles a WHERE a.slug = v.slug);$f$,
  slug, title, summary, body, cover_image_url, tags::text,
  coalesce(quote_literal(published_date::text), 'NULL'), is_published, sort_order)
FROM articles ORDER BY published_date DESC NULLS LAST, id;

-- availability_rules: natural key is the slot itself, (weekday, start_time,
-- end_time). start_time/end_time are `time without time zone` by design --
-- wall-clock Asia/Kolkata, resolved against App.Timezone in core/scheduler.
SELECT E'\n-- availability_rules --------------------------------------------------';
SELECT format($f$
WITH v (weekday, start_time, end_time, slot_minutes, active) AS (
  VALUES (%s::smallint, %L::time, %L::time, %s::int, %L::boolean)
), upd AS (
  UPDATE availability_rules a SET slot_minutes = v.slot_minutes, active = v.active
    FROM v WHERE a.weekday = v.weekday AND a.start_time = v.start_time AND a.end_time = v.end_time
    RETURNING 1
)
INSERT INTO availability_rules (weekday, start_time, end_time, slot_minutes, active)
SELECT v.* FROM v WHERE NOT EXISTS (
  SELECT 1 FROM availability_rules a WHERE a.weekday = v.weekday AND a.start_time = v.start_time AND a.end_time = v.end_time);$f$,
  weekday, start_time::text, end_time::text, slot_minutes, active)
FROM availability_rules ORDER BY weekday, start_time;

-- quiz_questions: course_id is resolved through courses.slug, never emitted as
-- a literal -- a fresh database's course ids do not match production's (5-12
-- live, different from a fresh chain), so an id literal would attach every
-- quiz to the wrong course. DISTINCT ON collapses production's duplicated rows
-- so a regenerated snapshot never carries the duplication forward.
SELECT E'\n-- quiz_questions ------------------------------------------------------';
SELECT format($f$
WITH v (course_slug, question, option_a, option_b, option_c, option_d, correct_option, sort_order) AS (
  VALUES (%L::text, %L::text, %L::text, %L::text, %L::text, %L::text, %L::char, %s::int)
), c AS (
  SELECT co.id FROM courses co, v WHERE co.slug = v.course_slug
), upd AS (
  UPDATE quiz_questions q SET option_a = v.option_a, option_b = v.option_b,
      option_c = v.option_c, option_d = v.option_d,
      correct_option = v.correct_option, sort_order = v.sort_order
    FROM v, c WHERE q.course_id = c.id AND q.question = v.question RETURNING 1
)
INSERT INTO quiz_questions (course_id, question, option_a, option_b, option_c, option_d, correct_option, sort_order)
SELECT c.id, v.question, v.option_a, v.option_b, v.option_c, v.option_d, v.correct_option, v.sort_order
FROM v, c WHERE NOT EXISTS (
  SELECT 1 FROM quiz_questions q WHERE q.course_id = c.id AND q.question = v.question);$f$,
  c.slug, q.question, q.option_a, q.option_b, q.option_c, q.option_d, q.correct_option, q.sort_order)
FROM (SELECT DISTINCT ON (course_id, question) * FROM quiz_questions ORDER BY course_id, question, id) q
JOIN courses c ON c.id = q.course_id
ORDER BY c.sort_order, q.sort_order;

-- certifications: natural key is (name, issuer, issued_on), and issued_on is
-- nullable ("this certification carries no date"). The NOT EXISTS probe uses
-- IS NOT DISTINCT FROM so two undated rows of the same certification match --
-- plain `=` would evaluate NULL = NULL to NULL and insert a duplicate on every
-- pass. Migration 054 enforces the same semantics in the schema with
-- UNIQUE NULLS NOT DISTINCT.
SELECT E'\n-- certifications ------------------------------------------------------';
SELECT format($f$
WITH v (name, issuer, issued_on, expires_on, credential_url, is_published, sort_order) AS (
  VALUES (%L::text, %L::text, %s::date, %s::date, %L::text, %L::boolean, %s::int)
), upd AS (
  UPDATE certifications c SET expires_on = v.expires_on, credential_url = v.credential_url,
      is_published = v.is_published, sort_order = v.sort_order
    FROM v WHERE c.name = v.name AND c.issuer = v.issuer
      AND c.issued_on IS NOT DISTINCT FROM v.issued_on RETURNING 1
)
INSERT INTO certifications (name, issuer, issued_on, expires_on, credential_url, is_published, sort_order)
SELECT v.* FROM v WHERE NOT EXISTS (
  SELECT 1 FROM certifications c WHERE c.name = v.name AND c.issuer = v.issuer
    AND c.issued_on IS NOT DISTINCT FROM v.issued_on);$f$,
  name, issuer, coalesce(quote_literal(issued_on::text), 'NULL'),
  coalesce(quote_literal(expires_on::text), 'NULL'), credential_url, is_published, sort_order)
FROM certifications ORDER BY sort_order, id;

-- publications: same nullable-date reasoning as certifications.
SELECT E'\n-- publications --------------------------------------------------------';
SELECT format($f$
WITH v (title, kind, venue, url, published_on, summary, is_published, sort_order) AS (
  VALUES (%L::text, %L::text, %L::text, %L::text, %s::date, %L::text, %L::boolean, %s::int)
), upd AS (
  UPDATE publications p SET kind = v.kind, url = v.url, summary = v.summary,
      is_published = v.is_published, sort_order = v.sort_order
    FROM v WHERE p.title = v.title AND p.venue = v.venue
      AND p.published_on IS NOT DISTINCT FROM v.published_on RETURNING 1
)
INSERT INTO publications (title, kind, venue, url, published_on, summary, is_published, sort_order)
SELECT v.* FROM v WHERE NOT EXISTS (
  SELECT 1 FROM publications p WHERE p.title = v.title AND p.venue = v.venue
    AND p.published_on IS NOT DISTINCT FROM v.published_on);$f$,
  title, kind, venue, url, coalesce(quote_literal(published_on::text), 'NULL'),
  summary, is_published, sort_order)
FROM publications ORDER BY sort_order, id;

-- SERIAL sequences are left where the inserts put them; nothing above sets an
-- id explicitly except profile's pinned id = 1, so no setval is needed.
SELECT E'\nCOMMIT;';
